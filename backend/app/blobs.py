"""Private file storage: project attachments and published works.

Files are never served from a public address. A download first passes the permission check in store.py or
network.py, which then redirects to a link that expires after a few minutes:

- STORAGE_BACKEND=s3: any S3-compatible bucket (AWS S3, Cloudflare R2, Backblaze B2, Supabase Storage, MinIO).
  The bucket must block public access; links are S3 presigned URLs.
- STORAGE_BACKEND=local (default): a folder on this server, for local development. Links point at
  /api/files/<token>, signed with SECRET_KEY.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import time
from pathlib import Path
from typing import Optional, Protocol
from urllib.parse import quote

LINK_TTL_SECONDS = 300


def content_disposition(filename: str) -> str:
    ascii_name = filename.encode("ascii", "ignore").decode().replace('"', "") or "download"
    return f"attachment; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(filename)}"


class BlobStore(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def delete(self, key: str) -> None: ...
    def download_url(self, key: str, filename: str, content_type: str) -> str: ...


class LocalBlobStore:
    def __init__(self, folder: Path, secret: str) -> None:
        self.folder = folder
        self.folder.mkdir(parents=True, exist_ok=True)
        self.secret = secret.encode()

    def _path(self, key: str) -> Path:
        # Keys are generated by the server ("attachments/file-…"); flatten them so nothing escapes the folder
        return self.folder / key.replace("/", "__").replace("\\", "__").replace("..", "_")

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self._path(key).write_bytes(data)

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def _sign(self, payload: bytes) -> str:
        return base64.urlsafe_b64encode(hmac.new(self.secret, payload, hashlib.sha256).digest()).decode().rstrip("=")

    def download_url(self, key: str, filename: str, content_type: str) -> str:
        payload = json.dumps({"k": key, "f": filename, "t": content_type, "e": int(time.time()) + LINK_TTL_SECONDS}).encode()
        token = base64.urlsafe_b64encode(payload).decode().rstrip("=")
        return f"/api/files/{token}.{self._sign(payload)}"

    def open_link(self, token: str) -> Optional[tuple[Path, str, str]]:
        """The file a signed link names, or None when the link is forged, altered or expired."""
        try:
            body, sig = token.rsplit(".", 1)
            payload = base64.urlsafe_b64decode(body + "=" * (-len(body) % 4))
        except (ValueError, TypeError):
            return None
        if not hmac.compare_digest(sig, self._sign(payload)):
            return None
        info = json.loads(payload)
        if info["e"] < time.time():
            return None
        path = self._path(info["k"])
        return (path, info["f"], info["t"]) if path.exists() else None


class S3BlobStore:
    def __init__(self) -> None:
        import boto3  # only needed when S3 is configured

        self.bucket = os.environ["S3_BUCKET"]
        self.client = boto3.client(
            "s3",
            endpoint_url=os.getenv("S3_ENDPOINT_URL") or None,
            region_name=os.getenv("S3_REGION") or None,
            # Falls back to the standard AWS credential chain when these are unset
            aws_access_key_id=os.getenv("S3_ACCESS_KEY_ID") or None,
            aws_secret_access_key=os.getenv("S3_SECRET_ACCESS_KEY") or None,
        )

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self.client.put_object(Bucket=self.bucket, Key=key, Body=data, ContentType=content_type)

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=key)

    def download_url(self, key: str, filename: str, content_type: str) -> str:
        return self.client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": self.bucket, "Key": key,
                "ResponseContentDisposition": content_disposition(filename),
                "ResponseContentType": content_type,
            },
            ExpiresIn=LINK_TTL_SECONDS,
        )


def open_blob_store(root: Path, secret: str) -> BlobStore:
    if os.getenv("STORAGE_BACKEND", "local").strip().lower() == "s3":
        return S3BlobStore()
    return LocalBlobStore(Path(os.getenv("NEMOSEARCH_FILES", root / "data" / "files")), secret)
